"""Export solver-generated data for the offline prototype."""
import json
from pathlib import Path

if __package__:
    from .demo_builder import MESSAGES, build_demo
else:
    from demo_builder import MESSAGES, build_demo

OUT = Path(__file__).resolve().parents[1] / "web" / "demo_data.js"


def main():
    data = build_demo()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// generated by solver/export_demo.py. do not edit by hand\n"
                   + "window.DEMO = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
                   encoding="utf-8")
    print(f"wrote {OUT.name}: {len(data['series'])} slider plans, default={data['defaultIdx']}")


if __name__ == "__main__":
    main()
